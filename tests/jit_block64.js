#!/usr/bin/env node
/* tests/jit_block64.js —— 64 位 ALU 与 jcc 直线块的逐位对拍
 *
 * 覆盖 REX.W 的 mov imm64 / mov r,r / add/sub/xor/test/cmp / add imm8 /
 * inc/dec，以及 jcc rel8 的 taken / not-taken 两条路径。
 *
 * 运行：JIT=1 ./build.sh wasm && node tests/jit_block64.js
 */
const fs = require("fs");
const path = require("path");
const { makeJitEnv } = require("./jit_hooks");

const ROOT = path.dirname(__dirname);
const WASM = path.join(ROOT, "web", "sim.wasm");

async function main() {
  const bytes = fs.readFileSync(WASM);
  const mod = new WebAssembly.Module(bytes);

  let inst = null;
  const jit = makeJitEnv(() => inst);
  inst = await WebAssembly.instantiate(mod, { env: jit.env });
  const w = inst.exports;
  if (w.sim_reset() !== 0) {
    console.error("[jit_block64] sim_reset failed");
    process.exit(1);
  }

  const P = 0x2000;
  const ram = w.sim_ram_base();
  const mem = new Uint8Array(w.memory.buffer);

  function reset(rip) {
    for (let i = 0; i < 16; i++) w.sim_set_reg(i, 0n);
    w.sim_set_flags(2n);
    w.sim_set_rip(BigInt(rip));
  }
  function snap() {
    const r = [];
    for (let i = 0; i < 16; i++) r.push(w.sim_get_reg(i));
    return { r, f: w.sim_get_flags(), rip: w.sim_get_rip() };
  }

  let bad = 0;
  function run_case(name, code, n) {
    code.forEach((b, i) => (mem[ram + P + i] = b));
    mem[ram + P + code.length] = 0xf4;   /* 块解码在这里停，避免读进旧字节 */

    reset(P);
    const jn = w.sim_jit_block(BigInt(P));
    const j = snap();

    reset(P);
    w.sim_run(n);
    const i = snap();

    if (jn !== n) {
      console.error(`[jit_block64] ${name}: block length ${jn} != ${n}`);
      bad++;
    }
    for (let k = 0; k < 16; k++) {
      if (j.r[k] !== i.r[k]) {
        console.error(
          `[jit_block64] ${name}: r${k} jit=0x${j.r[k].toString(16)} ` +
          `interp=0x${i.r[k].toString(16)}`
        );
        bad++;
      }
    }
    if (j.f !== i.f) {
      console.error(
        `[jit_block64] ${name}: flags jit=0x${j.f.toString(16)} ` +
        `interp=0x${i.f.toString(16)}`
      );
      bad++;
    }
    if (j.rip !== i.rip) {
      console.error(
        `[jit_block64] ${name}: rip jit=0x${j.rip.toString(16)} ` +
        `interp=0x${i.rip.toString(16)}`
      );
      bad++;
    }
    console.log(
      `${bad === 0 ? "PASS" : "FAIL"} ${name} n=${jn} ` +
      `rax=0x${j.r[0].toString(16)} rcx=0x${j.r[1].toString(16)} ` +
      `flags=0x${j.f.toString(16)} rip=0x${j.rip.toString(16)}`
    );
  }

  /* 64 位 ALU：12 条，无分支 */
  run_case("alu64", [
    0x48, 0xb8, 0x88, 0x77, 0x66, 0x55, 0x44, 0x33, 0x22, 0x11,
    0x48, 0xb9, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f,
    0x48, 0x01, 0xc8,
    0x48, 0x29, 0xc8,
    0x48, 0x31, 0xc9,
    0x48, 0x83, 0xc0, 0x05,
    0x48, 0xff, 0xc0,
    0x48, 0xff, 0xc9,
    0x48, 0x85, 0xc0,
    0x48, 0x39, 0xc8,
    0x48, 0x83, 0xf8, 0x05,
    0x90,
  ], 12);

  /* LEA（SIB/位移/RIP 相对）与 movzx/movsx */
  run_case("lea_movx", [
    0x48, 0xb8, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xb9, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0x8d, 0x14, 0x48,
    0x48, 0x8d, 0x5c, 0x88, 0x10,
    0x48, 0x8d, 0x6c, 0xcb, 0xf0,
    0xb9, 0x80, 0x00, 0x00, 0x00,
    0x0f, 0xbe, 0xd1,
    0x0f, 0xb6, 0xd9,
    0x48, 0x0f, 0xbe, 0xc9,
    0x48, 0x0f, 0xb7, 0xd9,
    0x48, 0x8d, 0x05, 0x00, 0x00, 0x00, 0x00,
    0x90,
  ], 12);

  /* 无 REX 的 8 位源是 AH/CH/DH/BH */
  run_case("movx_hi", [
    0xb8, 0x00, 0x80, 0x00, 0x00,
    0x0f, 0xbe, 0xcc,
    0x0f, 0xb6, 0xd4,
    0x48, 0x0f, 0xbe, 0xcc,
  ], 4);

  /* 内存操作数：C7 存立即数、8B 读、89 存、再读回 */
  run_case("mem_mov", [
    0x48, 0xb8, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xc7, 0x00, 0x78, 0x56, 0x34, 0x12,
    0x48, 0xc7, 0x40, 0x08, 0x11, 0x11, 0x11, 0x11,
    0x48, 0x8b, 0x08,
    0x48, 0x8b, 0x50, 0x08,
    0x48, 0x89, 0x48, 0x08,
    0x48, 0x8b, 0x58, 0x08,
    0x90,
  ], 8);

  /* 内存 ALU / cmp / test / inc / movzx / movsx */
  run_case("mem_alu", [
    0x48, 0xb8, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xc7, 0x00, 0x10, 0x00, 0x00, 0x00,
    0x48, 0xb9, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0x01, 0x08,
    0x48, 0x83, 0x28, 0x03,
    0x48, 0x83, 0x38, 0x12,
    0x48, 0x85, 0x00,
    0x48, 0xff, 0x00,
    0x48, 0x8b, 0x18,
    0x0f, 0xb6, 0x08,
    0x0f, 0xbe, 0x10,
    0x90,
  ], 12);

  run_case("mem_movx", [
    0x48, 0xb8, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xc7, 0x00, 0x80, 0x00, 0x00, 0x00,
    0x0f, 0xbe, 0x10,
    0x0f, 0xb6, 0x08,
    0x90,
  ], 5);

  /* ALU 两个内存方向：r/m 是目的 vs reg 是目的 */
  run_case("mem_alu_dir", [
    0x48, 0xb8, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xc7, 0x00, 0x0f, 0x00, 0x00, 0x00,
    0x48, 0xb9, 0xf0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0x23, 0x18,          /* and rbx,[rax]  -> 0x0f */
    0x48, 0x21, 0x08,          /* and [rax],rcx -> 0x00 */
    0x48, 0x8b, 0x10,          /* mov rdx,[rax] -> 0 */
    0x48, 0x83, 0x38, 0x00,    /* cmp qword [rax],0 */
    0x48, 0x8b, 0x58, 0x08,    /* mov rbx,[rax+8] (未初始化) */
    0x90,
  ], 9);

  /* 32 位内存写的宽度：不能覆盖高 32 位 */
  run_case("mem32_width", [
    0x48, 0xb8, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xb9, 0x88, 0x77, 0x66, 0x55, 0x44, 0x33, 0x22, 0x11,
    0x48, 0x89, 0x08,
    0xb9, 0x63, 0x00, 0x00, 0x00,
    0x89, 0x08,
    0x01, 0x08,
    0x48, 0x8b, 0x18,
    0x90,
  ], 8);

  /* RIP 相对与 SIB 的内存立即数/读回 */
  run_case("mem_rip", [
    0x48, 0xb8, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xc7, 0x05, 0xeb, 0x1f, 0x00, 0x00, 0x63, 0x00, 0x00, 0x00,
    0x48, 0x8b, 0x1d, 0xe4, 0x1f, 0x00, 0x00,
    0x90,
  ], 4);

  run_case("mem_sib", [
    0x48, 0xb8, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xb9, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x48, 0xc7, 0x44, 0x88, 0x10, 0x63, 0x00, 0x00, 0x00,
    0x48, 0x8b, 0x5c, 0x88, 0x10,
    0x90,
  ], 5);

  /* jcc taken：mov/cmp/je，块长 3；目标落在 mov eax,3 */
  run_case("jcc_taken", [
    0xb8, 0x01, 0x00, 0x00, 0x00,
    0x83, 0xf8, 0x01,
    0x74, 0x05,
    0xb8, 0x02, 0x00, 0x00, 0x00,
    0xb8, 0x03, 0x00, 0x00, 0x00,
    0x90,
  ], 3);

  /* jcc not-taken：cmp eax,2 -> ZF=0，RIP 落到 mov eax,2 */
  run_case("jcc_not_taken", [
    0xb8, 0x01, 0x00, 0x00, 0x00,
    0x83, 0xf8, 0x02,
    0x74, 0x05,
    0xb8, 0x02, 0x00, 0x00, 0x00,
    0xb8, 0x03, 0x00, 0x00, 0x00,
    0x90,
  ], 3);

  if (bad !== 0) {
    console.error(`[jit_block64] ${bad} mismatch(es)`);
    process.exit(1);
  }
  console.log("[jit_block64] PASS");
}

main().catch((e) => {
  console.error("[jit_block64] error:", e);
  process.exit(1);
});
